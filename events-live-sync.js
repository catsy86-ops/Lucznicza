/**
 * events-live-sync.js
 * Automatyczny harmonogram synchronizacji wydarzeń z portalu wSzczecinie.pl
 * Obsługuje:
 * - Cache w localStorage z TTL (Time To Live = 15 minut)
 * - Płynne odświeżanie danych w tle i na żądanie użytkownika
 * - Wizualny panel statusu świeżości danych (live badge, czas ostatniej synchronizacji, licznik wydarzeń)
 * - Bezpieczny fallback do wbudowanych danych i lokalnego snapshotu
 */

(function () {
  'use strict';

  const CACHE_KEY = 'szn_scraped_events_v1';
  const CACHE_META_KEY = 'szn_scraped_events_meta_v1';
  const REFRESH_INTERVAL_MS = 15 * 60 * 1000; // 15 minut

  class EventsLiveSync {
    constructor() {
      this.isSyncing = false;
      this.lastSyncTime = null;
      this.timerId = null;
      this.currentFilter = 'all';
      this.init();
    }

    init() {
      // Restore cached timestamp if available
      const meta = this.loadMeta();
      if (meta && meta.timestamp) {
        this.lastSyncTime = new Date(meta.timestamp);
      }

      // Try applying cached events immediately
      this.applyCachedEvents();

      // Schedule background periodic sync
      this.schedulePeriodicSync();

      // Hook up UI when DOM is ready
      if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', () => this.injectSyncStatusBar());
      } else {
        this.injectSyncStatusBar();
      }

      // Listen for section switches
      document.addEventListener('sectionChange', (e) => {
        if (e.detail && e.detail.section === 'events') {
          this.checkAndRefreshIfNeeded();
          this.updateStatusBarUI();
        }
      });
    }

    loadMeta() {
      try {
        const raw = localStorage.getItem(CACHE_META_KEY);
        return raw ? JSON.parse(raw) : null;
      } catch (e) {
        return null;
      }
    }

    saveMeta(count, source = 'wSzczecinie.pl') {
      try {
        const meta = {
          timestamp: Date.now(),
          count: count,
          source: source
        };
        localStorage.setItem(CACHE_META_KEY, JSON.stringify(meta));
        this.lastSyncTime = new Date(meta.timestamp);
      } catch (e) {
        console.warn('Nie udało się zapisać meta wydarzeń w localStorage', e);
      }
    }

    applyCachedEvents() {
      try {
        const raw = localStorage.getItem(CACHE_KEY);
        if (!raw) return;
        const cached = JSON.parse(raw);
        if (Array.isArray(cached) && cached.length > 0 && window.APP_DATA) {
          this.mergeEventsIntoAppData(cached);
        }
      } catch (e) {
        console.warn('Błąd odczytu cached events:', e);
      }
    }

    mergeEventsIntoAppData(newEvents) {
      const appData = window.APP_DATA || (typeof APP_DATA !== 'undefined' ? APP_DATA : null);
      if (!appData || !Array.isArray(appData.events)) return;
      
      const existing = appData.events;
      const mapByName = new Map();
      
      // Preserve existing local events
      for (const ev of existing) {
        mapByName.set(ev.name.trim().toLowerCase(), ev);
      }

      // Merge new scraped events
      for (const ev of newEvents) {
        const key = ev.name.trim().toLowerCase();
        mapByName.set(key, ev);
      }

      appData.events = Array.from(mapByName.values());

      // If on events section, re-render
      if (typeof window.renderEvents === 'function') {
        const activeTab = document.querySelector('.eft-btn.active');
        const filter = activeTab ? activeTab.dataset.filter || 'all' : 'all';
        if (typeof window.renderEventCards === 'function') {
          window.renderEventCards(filter);
        }
      }
    }

    async syncNow(isUserAction = false) {
      if (this.isSyncing) return;
      this.isSyncing = true;
      this.updateStatusBarUI(true);

      try {
        // Fetch the fresh snapshot generated by our scraper or live JSON endpoint
        const res = await fetch('/scraped-szczecin-events.json?t=' + Date.now(), { cache: 'no-store' });
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        const freshEvents = await res.json();

        if (Array.isArray(freshEvents) && freshEvents.length > 0) {
          localStorage.setItem(CACHE_KEY, JSON.stringify(freshEvents));
          this.saveMeta(freshEvents.length, 'wSzczecinie.pl');
          this.mergeEventsIntoAppData(freshEvents);

          if (isUserAction && typeof window.showToast === 'function') {
            window.showToast(`✨ Zaktualizowano wydarzenia (${freshEvents.length} ze Szczecina)`);
          }
        }
      } catch (err) {
        console.warn('Automatyczna synchronizacja wydarzeń z sieci:', err.message);
        if (isUserAction && typeof window.showToast === 'function') {
          window.showToast('ℹ️ Korzystasz z najnowszej dostępnej pamięci podręcznej');
        }
      } finally {
        this.isSyncing = false;
        this.updateStatusBarUI(false);
      }
    }

    checkAndRefreshIfNeeded() {
      const meta = this.loadMeta();
      if (!meta || !meta.timestamp || (Date.now() - meta.timestamp > REFRESH_INTERVAL_MS)) {
        this.syncNow(false);
      }
    }

    schedulePeriodicSync() {
      if (this.timerId) clearInterval(this.timerId);
      this.timerId = setInterval(() => {
        this.checkAndRefreshIfNeeded();
      }, REFRESH_INTERVAL_MS);
    }

    getTimeAgoText(date) {
      if (!date) return 'przed chwilą';
      const sec = Math.floor((Date.now() - date.getTime()) / 1000);
      if (sec < 60) return 'przed chwilą';
      const min = Math.floor(sec / 60);
      if (min < 60) return `${min} min temu`;
      const h = Math.floor(min / 60);
      if (h < 24) return `${h} godz. temu`;
      return date.toLocaleDateString('pl-PL', { day: 'numeric', month: 'short' });
    }

    injectSyncStatusBar() {
      const section = document.getElementById('section-events');
      if (!section) return;
      if (document.getElementById('eventsSyncBar')) return;

      const hero = section.querySelector('.section-hero');
      if (!hero) return;

      const bar = document.createElement('div');
      bar.id = 'eventsSyncBar';
      bar.className = 'events-sync-bar';
      bar.innerHTML = `
        <div class="esb-left">
          <span class="esb-pulse-dot"></span>
          <span class="esb-source">Live Feed: <strong>wSzczecinie.pl</strong></span>
          <span class="esb-separator">•</span>
          <span class="esb-freshness" id="esbFreshness">Aktualne</span>
        </div>
        <div class="esb-right">
          <button class="esb-refresh-btn" id="esbRefreshBtn" title="Wymuś synchronizację z wSzczecinie.pl" aria-label="Odśwież wydarzenia">
            <span class="esb-btn-icon">🔄</span>
            <span class="esb-btn-text">Synchronizuj</span>
          </button>
        </div>
      `;

      hero.after(bar);

      const btn = bar.querySelector('#esbRefreshBtn');
      if (btn) {
        btn.addEventListener('click', () => {
          this.syncNow(true);
        });
      }

      this.updateStatusBarUI();
    }

    updateStatusBarUI(syncing = false) {
      const bar = document.getElementById('eventsSyncBar');
      if (!bar) return;

      const btn = bar.querySelector('#esbRefreshBtn');
      const freshnessEl = bar.querySelector('#esbFreshness');
      const pulseDot = bar.querySelector('.esb-pulse-dot');

      if (syncing) {
        if (btn) btn.classList.add('loading');
        if (freshnessEl) freshnessEl.textContent = 'Pobieranie z portalu...';
        if (pulseDot) pulseDot.style.background = '#ffd700';
      } else {
        if (btn) btn.classList.remove('loading');
        const timeAgo = this.lastSyncTime ? this.getTimeAgoText(this.lastSyncTime) : 'dziś';
        const appData = window.APP_DATA || (typeof APP_DATA !== 'undefined' ? APP_DATA : null);
        const totalCount = appData && Array.isArray(appData.events) ? appData.events.length : 0;
        if (freshnessEl) {
          freshnessEl.innerHTML = `Zsynchronizowano: <em>${timeAgo}</em> (${totalCount} poz.)`;
        }
        if (pulseDot) pulseDot.style.background = '#43e97b';
      }
    }
  }

  // Expose global instance
  window.eventsLiveSync = new EventsLiveSync();
})();
